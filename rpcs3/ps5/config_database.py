#!/usr/bin/env python3
"""PS5: RPCS3's database of recommended settings, built into the title.

The desktop downloads it (rpcs3qt/config_database.cpp, from api.rpcs3.net) and
applies a game's entry when the game has no custom config. The console's
shareable build has no TLS for curl, so the title carries a copy instead:
this script downloads it and writes ps5_config_database.inc, one row per game
({"serial", "yaml"}, sorted by serial), which ps5_config_database.cpp looks
games up in. Run it before a release, and commit what it writes.

    python3 rpcs3/ps5/config_database.py [database.json]

With a file, it reads that instead of downloading.
"""

import json
import sys
import urllib.request
from pathlib import Path

URL = "https://api.rpcs3.net/config/?api=v1"
TARGET = Path(__file__).resolve().parent / "ps5_config_database.inc"
DELIMITER = "__ps5db__"

# Settings the console keeps whatever the database says: SPU Block Size (175
# entries ask for Mega, which froze GTA V for good on the console, build 188)
LEFT_OUT = {"SPU Block Size"}


def without_left_out(config):
    """The entry without LEFT_OUT's settings, and without a section left empty"""
    lines = [line for line in config.splitlines() if line.strip().split(":")[0] not in LEFT_OUT]
    kept = []
    for i, line in enumerate(lines):
        indent = len(line) - len(line.lstrip())
        following = lines[i + 1] if i + 1 < len(lines) else ""
        if line.rstrip().endswith(":") and len(following) - len(following.lstrip()) <= indent:
            continue
        kept.append(line)
    return "\n".join(kept)


def main():
    if len(sys.argv) > 1:
        data = Path(sys.argv[1]).read_bytes()
    else:
        request = urllib.request.Request(URL, headers={"User-Agent": "Kong3-build"})
        with urllib.request.urlopen(request, timeout=60) as response:
            data = response.read()
    database = json.loads(data)
    if database.get("return_code") != 0 or not isinstance(database.get("games"), dict):
        raise SystemExit(f"config database: unexpected answer (return_code {database.get('return_code')})")

    rows = []
    for serial, game in sorted(database["games"].items()):
        config = game.get("config") if isinstance(game, dict) else None
        if isinstance(config, str):
            config = without_left_out(config)
        if not isinstance(config, str) or not config.strip() or len(serial) != 9 or not serial.isalnum():
            continue
        if DELIMITER in config:
            raise SystemExit(f"config database: {serial}'s entry holds the delimiter")
        rows.append(f'{{"{serial}", R"{DELIMITER}({config}){DELIMITER}"}},')

    lines = [f"// Generated by rpcs3/ps5/config_database.py from {URL}",
             f"// (timestamp {database.get('timestamp', 'unknown')}): do not edit", ""] + rows + [""]
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {TARGET.name}: {len(rows)} games")


main()
