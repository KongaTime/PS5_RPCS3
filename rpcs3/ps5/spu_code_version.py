#!/usr/bin/env python3
# PS5: the SPU recompiler's fingerprint, for the SPU code cache's name.
#
# The cache (SPULLVMRecompiler.cpp, spu-code-*.pack) keeps compiled SPU code
# from one boot to the next. Its code is only good for the recompiler that
# made it: the code it emits and the spu_thread layout the code reads. Named
# for when the recompiler was compiled, every build that touched one of its
# headers threw every game's cache away; named for these files' contents, a
# build keeps it unless the recompiler itself changed.
#
# Usage: spu_code_version.py <out.h> <files...>
import hashlib
import sys


def main():
    out, files = sys.argv[1], sys.argv[2:]
    digest = hashlib.sha1()
    for path in sorted(files):
        digest.update(path.rsplit("/rpcs3/", 1)[-1].encode())
        digest.update(open(path, "rb").read().replace(b"\r\n", b"\n"))
    text = ("// Generated by rpcs3/ps5/spu_code_version.py: do not edit\n"
            f"#define PS5_SPU_CODE_VERSION \"{digest.hexdigest()[:16]}\"\n")
    try:
        if open(out).read() == text:
            return
    except OSError:
        pass
    with open(out, "w") as f:
        f.write(text)


main()
